-- تعبئة صفّ «المعايشة» للدفعات المبذورة قبل إضافته (الترحيل 0010).
--
-- كان هذا الإكمال عشر رحلاتٍ متسلسلة إلى القاعدة في كل إقلاع، لا تفعل شيئاً في
-- كل مرةٍ بعد الأولى. فصار ترحيلاً يجري مرةً واحدة أبداً وقت النشر، وبكلفة صفر
-- على طلبات المستخدمين.
--
-- وعبارةٌ واحدة بـCASE لا عشر: كلُّ عبارةٍ طلبٌ فرعيٌّ مستقلٌّ على D1، والسقف
-- خمسون. وواحدةٌ كذلك ذرّيّةٌ بطبعها، وD1 بلا معاملات.
--
-- والشرط `field = ''` مقصود: لا يُطمس ما حرّره المدير بيده. و`IN` يحصر
-- التعديل في الأسابيع المذكورة، فلا تُكتب NULL في أسبوعٍ لا فرع له في CASE.
