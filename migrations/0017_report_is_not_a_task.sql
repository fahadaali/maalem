-- التقريرُ الأسبوعي ليس مهمةً أسبوعية.
--
-- كان نصُّ خطة الأسبوعين الثاني والخامس يذكره بين مهامّهما:
--   "تقرير أسبوعي 1 + بدء المعايشة الميدانية"  و  "تقرير أسبوعي + تقرير المعايشة"
-- وهو واجبٌ قائمٌ كلَّ أسبوع من صفر إلى اثني عشر — بندُ ميثاق، وتذكيرُ خميس،
-- وشارةٌ في بطاقة الأسبوع — فذكرُه مهمةً في أسبوعين بعينهما تكرار.
--
-- وكلّف ذلك التكرارُ عَرَضين يراهما المشارك: صفٌّ في «المهام» اسمه «تقرير
-- أسبوعي…» يفتح نموذجَ تسليمِ مهمةٍ يُقيَّم من ستّ عشرة — لا التقرير؛ وخانةٌ
-- داخل التقرير نفسه تسأل صاحبَه: «هل أنجزتَ تقريراً أسبوعياً؟».
--
-- والمطابقةُ تامّةٌ لا جزئية: نصٌّ حرّره المديرُ بيده لا يُمَسّ.

-- جدول الخطة
UPDATE ProgramWeek SET task = 'بدء المعايشة الميدانية' WHERE task = 'تقرير أسبوعي 1 + بدء المعايشة الميدانية';
UPDATE ProgramWeek SET task = 'تقرير المعايشة' WHERE task = 'تقرير أسبوعي + تقرير المعايشة';

-- المهمة المنشورة للمشاركين
UPDATE Assignment SET title = 'بدء المعايشة الميدانية' WHERE title = 'تقرير أسبوعي 1 + بدء المعايشة الميدانية';
UPDATE Assignment SET title = 'تقرير المعايشة' WHERE title = 'تقرير أسبوعي + تقرير المعايشة';

-- خانةُ التقرير الدائرة على نفسها.
--
-- والشرطُ الثاني جوهريّ: مهمةٌ رصد عليها مشاركٌ في تقريره لا تُحذف فيُمحى رصدُه
-- معها — وهو عينُ ما يرفضه محرّرُ المهام في لوحة المدير، وموجَبُ أن التقرير
-- وثيقةٌ لا تتبدّل بتعديلٍ لاحق على الجدول.
DELETE FROM WeekTask
WHERE title LIKE 'تقرير أسبوعي%'
  AND id NOT IN (SELECT taskId FROM WeeklyReportTask);
